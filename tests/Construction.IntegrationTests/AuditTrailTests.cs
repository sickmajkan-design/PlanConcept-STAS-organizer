    }

    [Fact]
    public async Task The_actor_s_details_are_copied_in_rather_than_looked_up_later()
    {
        // The account can be renamed, promoted or deleted afterwards. The
        // trail has to say who did it at the time — a join would either
        // rewrite history or leave a dangling id.
        var actor = await InScope(scope =>
            TestData.SeedUserAsync(scope, UserRole.Admin, email: "before@construction.test"));

        var employee = await InScope(scope =>
        {
            ActAs(scope, actor);
            return TestData.SeedEmployeeAsync(scope);
        });

        await InScope(async scope =>
        {
            var tracked = await scope.Db.Users.SingleAsync(u => u.Id == actor.Id);
            tracked.Email = "after@construction.test";
            tracked.Role = UserRole.Worker;
            await scope.Db.SaveChangesAsync();
        });

        var entry = Assert.Single(await TrailFor<Employee>(employee.Id));

        Assert.Equal("before@construction.test", entry.UserEmail);
        Assert.Equal(UserRole.Admin, entry.UserRole);
    }

    [Fact]
    public async Task A_change_with_nobody_signed_in_is_still_recorded()
    {
        // Background jobs and migrations write too. Dropping those rows
        // because there is no user would leave gaps exactly where an
        // unexplained change is most alarming.
        var employee = await InScope(scope =>
        {
            scope.CurrentUser.SignOut();
            return TestData.SeedEmployeeAsync(scope);
        });

        var entry = Assert.Single(await TrailFor<Employee>(employee.Id));

        Assert.Null(entry.UserId);
        Assert.Null(entry.UserEmail);
        Assert.Equal(AuditAction.Created, entry.Action);
    }

    // ---- what is deliberately not recorded --------------------------------

    [Fact]
    public async Task A_password_change_does_not_put_the_hash_in_the_trail()
    {
        // The reason NotAuditedAttribute exists. Without it a password change
        // writes both the old and the new hash into a table that is read by
        // administrators and outlives the account — turning the audit trail
        // into an offline-cracking target with a change history attached.
        var admin = await InScope(scope => TestData.SeedUserAsync(scope, UserRole.SuperAdmin));
        var subject = await InScope(scope => TestData.SeedUserAsync(scope, UserRole.Worker));

        var hashBefore = await InScope(scope => scope.Db.Users
            .Where(u => u.Id == subject.Id)
            .Select(u => u.PasswordHash)
            .SingleAsync());

        await InScope(scope =>
        {
            ActAs(scope, admin);
            return scope.Send(new SetUserPasswordCommand
            {
                Id = subject.Id,
                NewPassword = "Replaced1234!"
            });
        });

        var hashAfter = await InScope(scope => scope.Db.Users
            .Where(u => u.Id == subject.Id)
            .Select(u => u.PasswordHash)
            .SingleAsync());

        Assert.NotEqual(hashBefore, hashAfter);

        var trail = await TrailFor<User>(subject.Id);

        foreach (var entry in trail)
        {
            Assert.DoesNotContain("PasswordHash", ChangesOf(entry).Keys);

            // Not just the key — the value must not have landed under some
            // other name either.
            Assert.DoesNotContain(hashBefore, entry.ChangesJson);
            Assert.DoesNotContain(hashAfter, entry.ChangesJson);
        }
    }

    [Fact]
    public async Task Nothing_that_looks_like_a_credential_is_ever_recorded()
    {
        // The safety net, asserted across every row the whole suite has
        // written rather than on one entity — the risk is a field added later
        // by somebody who did not read the attribute.
        var suspicious = new[] { "password", "hash", "token", "secret" };

        var keys = await InScope(async scope =>
        {
            var rows = await scope.Db.AuditEntries
                .AsNoTracking()
                .Select(a => a.ChangesJson)
                .Take(2000)
                .ToListAsync();

            return rows
                .SelectMany(json =>
                    JsonSerializer.Deserialize<Dictionary<string, Change>>(json, Json)!.Keys)
                .Distinct()
                .ToList();
        });

        Assert.NotEmpty(keys);

        Assert.All(keys, key => Assert.DoesNotContain(
            suspicious,
            fragment => key.Contains(fragment, StringComparison.OrdinalIgnoreCase)));
    }

    [Fact]
    public async Task High_volume_machine_chatter_is_not_audited()
    {
        // Auditing GPS would add a row per ping — about a million a month for
        // a hundred-person crew — to record something no investigation will
        // ever ask about.
        var (employee, user) = await InScope(async scope =>
        {
            var employee = await TestData.SeedEmployeeAsync(scope);
            var user = await TestData.SeedUserAsync(scope, UserRole.Worker, employee.Id);
            return (employee, user);
        });

        var before = await InScope(scope => scope.Db.AuditEntries.CountAsync());

        await InScope(scope =>
        {
            scope.CurrentUser.SignInAs(user.Id, user.Role, employee.Id, user.Email);
            return scope.Send(new ReportLocationsCommand
            {
                Pings =
                [
                    new LocationPing
                    {
                        Latitude = 45.81,
                        Longitude = 15.98,
                        Timestamp = new DateTime(2026, 8, 5, 12, 0, 0, DateTimeKind.Utc)
                    }
                ]
            });
        });

        var after = await InScope(scope => scope.Db.AuditEntries.CountAsync());

        Assert.Equal(before, after);
    }

