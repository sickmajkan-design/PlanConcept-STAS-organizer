/// <summary>
/// Who changed what, and when.
/// </summary>
/// <remarks>
/// <para>
/// The trail is written by a persistence interceptor, so what needs proving is
/// not that a method works but that there is no way around it: a handler that
/// modifies an audited entity gets a row whether or not anybody remembered.
/// </para>
/// <para>
/// The security half matters as much as the coverage half. An audit trail is a
/// long-lived, administrator-readable copy of every field that changed, which
/// makes it the second place a password hash can come to rest — and unlike the
/// first, it outlives the account.
/// </para>
/// </remarks>
[Collection(DatabaseCollection.Name)]
public class AuditTrailTests : IntegrationTestBase
{
    public AuditTrailTests(DatabaseFixture fixture) : base(fixture)
    {
    }

    private static readonly JsonSerializerOptions Json = new(JsonSerializerDefaults.Web);

    private Task<List<AuditEntry>> TrailFor<T>(Guid id) =>
        InScope(scope => scope.Db.AuditEntries
            .AsNoTracking()
            .Where(a => a.EntityName == typeof(T).Name && a.EntityId == id)
            .OrderBy(a => a.Id)
            .ToListAsync());

    /// <summary>
    /// The most recent entry for a record.
    /// </summary>
    /// <remarks>
    /// Seeding an entity is itself an audited creation, so a test that seeds
    /// and then edits has two rows and wants the second. That the seed is
    /// recorded at all is the interceptor working — there is no way to write
    /// an audited entity without leaving a trail, including from a test
    /// helper.
    /// </remarks>
    private async Task<AuditEntry> LatestFor<T>(Guid id)
    {
        var trail = await TrailFor<T>(id);
        return trail[^1];
    }

    private static Dictionary<string, Change> ChangesOf(AuditEntry entry) =>
        JsonSerializer.Deserialize<Dictionary<string, Change>>(entry.ChangesJson, Json)!;

    private sealed record Change(string? From, string? To);

    private static void ActAs(TestScope scope, User user) =>
        scope.CurrentUser.SignInAs(user.Id, user.Role, null, user.Email);

    private static CreateEmployeeCommand NewEmployee(string number) => new()
    {
        EmployeeNumber = number,
        FirstName = "Ivan",
        LastName = "Horvat",
        Position = "Site Manager",
        EmploymentDate = new DateOnly(2020, 3, 1),
        Status = EmployeeStatus.Active
    };

    // ---- recording -------------------------------------------------------

    [Fact]
    public async Task Creating_a_record_is_written_down_with_what_it_started_as()
    {
        var employee = await InScope(scope =>
            scope.Send(NewEmployee($"EMP-AUD-{Guid.NewGuid().ToString("N")[..6]}")));

        var entry = Assert.Single(await TrailFor<Employee>(employee.Id));

        Assert.Equal(AuditAction.Created, entry.Action);
        Assert.Equal("Employee", entry.EntityName);

        var changes = ChangesOf(entry);

        // The whole starting state, so the trail can describe the record
        // without the record still existing.
        Assert.Equal("Ivan", changes["FirstName"].To);
        Assert.Equal("Horvat", changes["LastName"].To);
        Assert.Equal("Site Manager", changes["Position"].To);
        Assert.All(changes.Values, change => Assert.Null(change.From));
    }

    [Fact]
    public async Task A_created_record_is_filed_under_the_id_it_actually_got()
    {
        // The interceptor reads the key before the insert, which only works
        // because EF generates Guid keys on the client. Were they generated by
        // the database, every creation would be filed under an empty id and
        // the trail would be unusable in exactly the case it is needed most.
        var employee = await InScope(scope =>
            scope.Send(NewEmployee($"EMP-ID-{Guid.NewGuid().ToString("N")[..6]}")));

        var entry = Assert.Single(await TrailFor<Employee>(employee.Id));

        Assert.NotEqual(Guid.Empty, entry.EntityId);
        Assert.Equal(employee.Id, entry.EntityId);
    }

    [Fact]
    public async Task An_edit_records_only_what_moved()
    {
        var employee = await InScope(scope => TestData.SeedEmployeeAsync(scope));

        await InScope(scope => scope.Send(new UpdateEmployeeCommand
        {
            Id = employee.Id,
            EmployeeNumber = employee.EmployeeNumber,
            FirstName = "Petra",
            LastName = employee.LastName,
            Position = employee.Position,
            EmploymentDate = employee.EmploymentDate,
            Status = EmployeeStatus.OnLeave
        }));

        var entry = await LatestFor<Employee>(employee.Id);
        var changes = ChangesOf(entry);

        Assert.Equal(AuditAction.Updated, entry.Action);

        Assert.Equal("Ivan", changes["FirstName"].From);
        Assert.Equal("Petra", changes["FirstName"].To);
        Assert.Equal("Active", changes["Status"].From);
        Assert.Equal("OnLeave", changes["Status"].To);

        // The handler assigns every field from the command, so EF marks them
        // all modified. Recording those would bury the two real changes in
        // "Position: Site Manager → Site Manager".
        Assert.DoesNotContain("LastName", changes.Keys);
        Assert.DoesNotContain("Position", changes.Keys);
    }

    [Fact]
    public async Task An_enum_is_recorded_by_name_and_not_by_number()
    {
        // A number is meaningless to whoever reads the trail, and renumbering
        // the enum later would silently rewrite what the history says
        // happened.
        var employee = await InScope(scope => TestData.SeedEmployeeAsync(scope));

        await InScope(scope => scope.Send(new UpdateEmployeeCommand
        {
            Id = employee.Id,
            EmployeeNumber = employee.EmployeeNumber,
            FirstName = employee.FirstName,
            LastName = employee.LastName,
            Position = employee.Position,
            EmploymentDate = employee.EmploymentDate,
            Status = EmployeeStatus.Terminated
        }));

        var changes = ChangesOf(await LatestFor<Employee>(employee.Id));

        Assert.Equal("Terminated", changes["Status"].To);
    }

    [Fact]
    public async Task A_save_that_changed_nothing_leaves_no_trace()
    {
        // Re-saving a form untouched is the most common write in an admin
        // panel. A row for each would make the trail mostly noise, in the one
        // place noise is most expensive to read through.
        var employee = await InScope(scope => TestData.SeedEmployeeAsync(scope));

        var unchanged = new UpdateEmployeeCommand
        {
            Id = employee.Id,
            EmployeeNumber = employee.EmployeeNumber,
            FirstName = employee.FirstName,
            LastName = employee.LastName,
            Position = employee.Position,
            EmploymentDate = employee.EmploymentDate,
            Status = employee.Status
        };

        var before = (await TrailFor<Employee>(employee.Id)).Count;

        await InScope(scope => scope.Send(unchanged));

        Assert.Equal(before, (await TrailFor<Employee>(employee.Id)).Count);
    }

    [Fact]
    public async Task A_soft_delete_is_recorded_as_a_deletion_and_not_as_an_edit()
    {
        // The soft-delete interceptor has already turned this into a
        // modification by the time the trail sees it. Recorded naively it
        // would read "IsDeleted: false → true", which is true, unhelpful, and
        // impossible to filter on.
        var employee = await InScope(scope => TestData.SeedEmployeeAsync(scope));

        await InScope(scope => scope.Send(new DeleteEmployeeCommand(employee.Id)));

        var entry = await LatestFor<Employee>(employee.Id);

        Assert.Equal(AuditAction.Deleted, entry.Action);
    }

    [Fact]
    public async Task A_soft_delete_does_not_pretend_the_data_was_lost()
    {
        // A soft-deleted row is still on disk under its flag, so there is
        // nothing to preserve a copy of. Recording the whole record as
        // "value → null" would read as destruction, which is the opposite of
        // what happened and the opposite of what a recovery would need.
        //
        // This is also what pins the interceptor ordering. Registered before
        // the soft-delete interceptor, the entity would still be in the
        // Deleted state here and would get the full snapshot below — while
        // still being reported as Deleted, which is why asserting the action
        // alone was not enough.
        var employee = await InScope(scope => TestData.SeedEmployeeAsync(scope));

        await InScope(scope => scope.Send(new DeleteEmployeeCommand(employee.Id)));

        var entry = await LatestFor<Employee>(employee.Id);
        var changes = ChangesOf(entry);

        Assert.Equal(AuditAction.Deleted, entry.Action);
        Assert.DoesNotContain("FirstName", changes.Keys);
        Assert.DoesNotContain("EmployeeNumber", changes.Keys);
    }

    [Fact]
    public async Task A_hard_delete_records_what_was_lost()
    {
        // The other branch, and a real path: removing a posting that has not
        // started yet deletes the row outright rather than end-dating it,
        // because there is nothing to preserve. This is the last moment the
        // values exist, so the trail takes a copy.
        var employee = await InScope(scope => TestData.SeedEmployeeAsync(scope));
        var project = await InScope(scope => TestData.SeedProjectAsync(scope));

        var startsNextWeek = DateOnly.FromDateTime(DateTime.UtcNow).AddDays(7);

        await InScope(scope => scope.Send(
            new AssignEmployeeToProjectCommand(employee.Id, project.Id)
            {
                StartDate = startsNextWeek
            }));

        var postingId = await InScope(scope => scope.Db.EmployeeProjects
            .Where(ep => ep.EmployeeId == employee.Id && ep.ProjectId == project.Id)
            .Select(ep => ep.Id)
            .SingleAsync());

        await InScope(scope => scope.Send(
            new RemoveEmployeeFromProjectCommand(employee.Id, project.Id)));

        var entry = await LatestFor<EmployeeProject>(postingId);
        var changes = ChangesOf(entry);

        Assert.Equal(AuditAction.Deleted, entry.Action);

        // Everything the row held, on its way out.
        Assert.Equal(employee.Id.ToString(), changes["EmployeeId"].From);
        Assert.Equal(project.Id.ToString(), changes["ProjectId"].From);
        Assert.All(changes.Values, change => Assert.Null(change.To));
    }

    [Fact]
    public async Task The_trail_outlives_the_record_it_describes()
    {
        // The point of the whole thing. A deleted employee's history has to
        // survive the deletion, or the trail says least about the changes most
        // worth asking about.
        var employee = await InScope(scope =>
            scope.Send(NewEmployee($"EMP-GONE-{Guid.NewGuid().ToString("N")[..6]}")));

        await InScope(scope => scope.Send(new DeleteEmployeeCommand(employee.Id)));

        var trail = await TrailFor<Employee>(employee.Id);

        Assert.Equal(2, trail.Count);
        Assert.Equal(AuditAction.Created, trail[0].Action);
        Assert.Equal(AuditAction.Deleted, trail[1].Action);
    }

