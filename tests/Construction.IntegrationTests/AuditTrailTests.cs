    [Fact]
    public async Task The_trail_can_be_read_as_what_one_person_did()
    {
        // The other question an investigation asks, and the reason for the
        // second index.
        var actor = await InScope(scope => TestData.SeedUserAsync(scope, UserRole.Admin));

        var first = await InScope(scope =>
        {
            ActAs(scope, actor);
            return TestData.SeedEmployeeAsync(scope);
        });

        var second = await InScope(scope =>
        {
            ActAs(scope, actor);
            return TestData.SeedEmployeeAsync(scope);
        });

        var page = await InScope(scope => scope.Send(new GetAuditTrailQuery
        {
            UserId = actor.Id,
            PageSize = 100
        }));

        Assert.All(page.Items, item => Assert.Equal(actor.Id, item.UserId));

        var touched = page.Items.Select(i => i.EntityId).ToList();
        Assert.Contains(first.Id, touched);
        Assert.Contains(second.Id, touched);
    }

    [Fact]
    public async Task The_trail_can_be_narrowed_to_one_kind_of_action()
    {
        var actor = await InScope(scope => TestData.SeedUserAsync(scope, UserRole.Admin));

        var employee = await InScope(scope =>
        {
            ActAs(scope, actor);
            return TestData.SeedEmployeeAsync(scope);
        });

        await InScope(scope =>
        {
            ActAs(scope, actor);
            return scope.Send(new DeleteEmployeeCommand(employee.Id));
