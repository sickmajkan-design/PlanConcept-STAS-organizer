    [Fact]
    public async Task An_id_without_a_type_is_refused()
    {
        // Not pedantry: the index is keyed on the pair, so an id-only query
        // cannot use it and would scan the largest table in the system.
        await Assert.ThrowsAsync<Application.Common.Exceptions.ValidationException>(() =>
            InScope(scope => scope.Send(new GetAuditTrailQuery { EntityId = Guid.NewGuid() })));
    }

    [Fact]
    public async Task Paging_the_trail_neither_repeats_nor_skips_an_entry()
    {
        // Several rows share a timestamp — one save stamps them all from the
        // same clock reading — so ordering by time alone leaves their relative
        // order undefined between the two queries that fetch page one and page
        // two.
        var actor = await InScope(scope => TestData.SeedUserAsync(scope, UserRole.Admin));

        for (var i = 0; i < 12; i++)
        {
            await InScope(scope =>
            {
                ActAs(scope, actor);
                return TestData.SeedEmployeeAsync(scope);
            });
        }

        var seen = new List<long>();

        for (var page = 1; page <= 3; page++)
        {
            var result = await InScope(scope => scope.Send(new GetAuditTrailQuery
            {
                UserId = actor.Id,
                PageNumber = page,
                PageSize = 5
            }));

            seen.AddRange(result.Items.Select(i => i.Id));
        }

        Assert.Equal(12, seen.Count);
        Assert.Equal(12, seen.Distinct().Count());
    }
